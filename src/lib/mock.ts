export function generateMockHistory(hours: number) {
  const now = Math.floor(Date.now() / 1000)
  const step = Math.max(60, Math.floor((hours * 3600) / 40))
  const count = Math.min(60, Math.floor((hours * 3600) / step))
  const metrics = []
  const ping = []

  for (let i = count; i >= 0; i--) {
    const ts = now - i * step
    const wave = Math.sin(i / 5) * 15 + Math.cos(i / 3) * 10
    const cpu = Math.max(5, Math.min(95, 35 + wave + Math.random() * 8))
    const mem = (16 + Math.sin(i / 8) * 4) * 1024 * 1024 * 1024
    const disk = 420 * 1024 * 1024 * 1024 + i * 50 * 1024 * 1024
    const rx = Math.max(1024 * 1024, (15 + wave / 2) * 1024 * 1024)
    const tx = Math.max(1024 * 1024, (25 + wave) * 1024 * 1024)

    metrics.push({
      ts,
      cpu,
      mem_used: mem,
      disk_used: disk,
      net_rx: rx,
      net_tx: tx,
    })

    ping.push({
      task_id: 1,
      ts,
      latency: Math.max(2, 12 + Math.random() * 4 + (i === 15 ? 45 : 0)),
      loss: i === 15 ? 5 : 0,
    })
    ping.push({
      task_id: 2,
      ts,
      latency: Math.max(15, 38 + Math.sin(i / 4) * 6 + Math.random() * 5),
      loss: 0,
    })
    ping.push({
      task_id: 3,
      ts,
      latency: Math.max(90, 125 + Math.cos(i / 6) * 12 + Math.random() * 10),
      loss: 0,
    })
  }

  return {
    metrics,
    ping,
    probes: {
      "1": "东京 CT",
      "2": "香港 CN2",
      "3": "洛杉矶 9929",
    },
    loss: {
      "1": 0.5,
    },
  }
}
